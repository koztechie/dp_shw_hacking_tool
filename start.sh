#!/bin/bash
set -e

# Антикрихкість: автоматично визначаємо директорію, де лежить скрипт, 
# і переходимо в неї. Тепер скрипт можна запускати звідки завгодно!
cd "$(dirname "$0")"

# Перевірка цілісності віртуального середовища
if [ ! -f "venv/bin/python" ]; then
    echo "❌ Помилка: Віртуальне середовище (venv) не знайдено!"
    echo "Будь ласка, спочатку налаштуйте проект згідно з документацією."
    exit 1
fi

echo "====================================================="
echo "⚡ DP_SHW_Hacking_Tool запускається..."
echo "📊 Відкрий браузер за адресою: http://127.0.0.1:8000"
echo "🛑 Для зупинки сервера натисніть комбінацію Ctrl+C"
echo "====================================================="

# Використовуємо exec для передачі керування процесу Python, 
# що дозволяє коректно обробляти сигнали завершення (Ctrl+C)
exec ./venv/bin/python src/api/main.py
